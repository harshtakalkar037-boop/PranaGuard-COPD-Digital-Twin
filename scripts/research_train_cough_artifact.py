#!/usr/bin/env python3
"""Train the calibrated cough artifact for the platform's Model B and capture eval metrics/json.
Same feature pipeline + protocol as the research experiment. Artifact = joblib pipeline."""
import os, json
import sklearn
from pathlib import Path
import numpy as np, pandas as pd, joblib
from sklearn.ensemble import RandomForestClassifier
from sklearn.calibration import CalibratedClassifierCV
from sklearn.metrics import (roc_auc_score, average_precision_score, accuracy_score, f1_score,
                             brier_score_loss, log_loss, confusion_matrix)

ROOT = Path(os.environ.get('RESEARCH_ROOT', 'external-research/pranaguard-unified-copd-dataset'))
SCRIPT_DIR = Path(__file__).resolve().parent
OUT = Path(os.environ.get('RESEARCH_OUT', SCRIPT_DIR.parent/'backend'/'app'/'research'/'artifacts')); OUT.mkdir(parents=True, exist_ok=True)
SEED = 20261108

f = pd.read_parquet(ROOT/'data/processed/audio_features/cough_features.parquet')
FEATS = [c for c in f.columns if c.startswith(('mfcc','logmel')) or
         c in ('zcr_mean','zcr_std','rms_mean','rms_std','spectral_centroid_mean_hz','spectral_centroid_std_hz')]
tr = f[f['publisher_split']=='train']; te = f[f['publisher_split']=='test']
Xtr, ytr = tr[FEATS].values, (tr['class_label']=='COPD').astype(int).values
Xte, yte = te[FEATS].values, (te['class_label']=='COPD').astype(int).values

model = CalibratedClassifierCV(
    RandomForestClassifier(n_estimators=300, min_samples_leaf=2,
                           class_weight='balanced_subsample', random_state=SEED, n_jobs=2),
    cv=5, method='sigmoid')
model.fit(Xtr, ytr)
p = model.predict_proba(Xte)[:,1]
yhat = (p>=0.5).astype(int)
tn, fp, fn, tp = confusion_matrix(yte, yhat).ravel()
metrics = {
 'model_id': 'cough-copd-rf-calibrated', 'version': '1.0.0', 'features': FEATS,
 'feature_version': 'mfcc13+logmel13+zcr+rms+centroid v1',
 'dataset': 'Cough-COPD(CC) Zenodo 14881818 (CC-BY-4.0)',
 'protocol': 'publisher train/test split; train-only sigmoid calibration (cv=5); threshold 0.5',
 'train': {'n': int(len(tr)), 'COPD': int(ytr.sum()), 'Healthy': int((1-ytr).sum())},
 'test':  {'n': int(len(te)), 'COPD': int(yte.sum()), 'Healthy': int((1-yte).sum())},
 'test_metrics': {
   'auroc': float(roc_auc_score(yte, p)), 'auprc': float(average_precision_score(yte, p)),
   'prevalence_copd': float(yte.mean()), 'accuracy': float(accuracy_score(yte, yhat)),
   'f1_copd': float(f1_score(yte, yhat)), 'sensitivity_copd': float(tp/(tp+fn)),
   'specificity': float(tn/(tn+fp)), 'precision_copd': float(tp/(tp+fp)),
   'brier': float(brier_score_loss(yte, p)), 'log_loss': float(log_loss(yte, np.clip(p,1e-7,1-1e-7))),
   'confusion': {'tn': int(tn), 'fp': int(fp), 'fn': int(fn), 'tp': int(tp)}},
 'limitations': ['No participant identifiers published -> participant independence cannot be verified; file-level upper bounds',
                 'COPD sensitivity ~0.58 at threshold 0.5 (v2 calibrated); low sensitivity at conservative thresholds',
                 'Not a diagnostic; not a validated screening tool; not exacerbation prediction']}
joblib.dump({'model': model, 'features': FEATS, 'meta': metrics}, OUT/'cough_model.joblib', compress=3)
# Global feature importance (mean decrease-in-impurity across calibrated folds) — descriptive, not causal, not SHAP.
imp = np.mean([getattr(c, 'estimator', None).feature_importances_ if getattr(c, 'estimator', None) is not None
               else c.estimator_.feature_importances_ for c in model.calibrated_classifiers_], axis=0)
order = np.argsort(imp)[::-1]
metrics['global_feature_importance'] = [{'feature': FEATS[i], 'importance': round(float(imp[i]), 5)} for i in order[:20]]
metrics['global_feature_importance_note'] = 'Mean decrease-in-impurity across calibrated folds; descriptive only, not causal; generated by this module (NOT the Digital-Twin SHAP implementation).'
metrics['runtime_environment'] = f'trained and re-saved under scikit-learn {sklearn.__version__}, numpy {np.__version__} (backend requirements pins)'
(OUT/'cough_model_eval.json').write_text(json.dumps(metrics, indent=1))
print(json.dumps(metrics['test_metrics'], indent=1))
print('artifact bytes:', (OUT/'cough_model.joblib').stat().st_size)
